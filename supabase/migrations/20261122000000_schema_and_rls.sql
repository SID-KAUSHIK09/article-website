-- Schema and row level security for the article website.
--
-- The browser talks to Supabase with the public anon key, so anyone can call
-- the REST API directly. These policies are what actually protect the data:
--   * anyone can read categories and articles
--   * only users listed in public.admins can create articles or manage categories
--   * a user can only edit or delete the articles they wrote (author_id)
--
-- Safe to run on a database that already has the tables: everything is
-- "if not exists" / "or replace", and policies are dropped and recreated.

-- ---------------------------------------------------------------- tables

create table if not exists public.categories (
  id            text primary key,              -- slug used in URLs, e.g. 'poems'
  name          text not null,
  description   text,
  display_order integer not null default 0,
  created_at    timestamptz not null default now()
);

create table if not exists public.articles (
  id         bigint generated by default as identity primary key,
  title      text not null,
  content    text not null,
  category   text not null references public.categories (id) on delete cascade,
  date       text,                             -- display date in Hindi, e.g. '5 जनवरी 2026'
  created_at timestamptz not null default now()
);

-- Who wrote each article. Filled in automatically from the signed-in user,
-- so the app never has to send it.
alter table public.articles
  add column if not exists author_id uuid
    references auth.users (id) on delete set null
    default auth.uid();

create index if not exists articles_category_idx on public.articles (category);
create index if not exists articles_author_idx   on public.articles (author_id);

-- Users allowed into the admin panel. Add a row per writer, e.g.
--   insert into public.admins (user_id)
--   select id from auth.users where email = 'writer@example.com';
create table if not exists public.admins (
  user_id    uuid primary key references auth.users (id) on delete cascade,
  created_at timestamptz not null default now()
);

-- security definer so the check works even though admins has RLS on and no
-- select policy; search_path is pinned so it cannot be hijacked.
create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (select 1 from public.admins where user_id = auth.uid());
$$;

revoke all on function public.is_admin() from public;
grant execute on function public.is_admin() to anon, authenticated;

-- ---------------------------------------------------------------- RLS

alter table public.categories enable row level security;
alter table public.articles   enable row level security;
alter table public.admins     enable row level security;  -- no policies: not readable through the API

-- categories: public read, admin write
drop policy if exists "Categories are public"         on public.categories;
drop policy if exists "Admins can add categories"     on public.categories;
drop policy if exists "Admins can edit categories"    on public.categories;
drop policy if exists "Admins can delete categories"  on public.categories;

create policy "Categories are public"
  on public.categories for select
  to anon, authenticated
  using (true);

create policy "Admins can add categories"
  on public.categories for insert
  to authenticated
  with check ((select public.is_admin()));

create policy "Admins can edit categories"
  on public.categories for update
  to authenticated
  using ((select public.is_admin()))
  with check ((select public.is_admin()));

create policy "Admins can delete categories"
  on public.categories for delete
  to authenticated
  using ((select public.is_admin()));

-- articles: public read, admins publish, authors edit their own
drop policy if exists "Articles are public"                 on public.articles;
drop policy if exists "Admins can publish as themselves"    on public.articles;
drop policy if exists "Authors can edit their own articles" on public.articles;
drop policy if exists "Authors can delete their own articles" on public.articles;

create policy "Articles are public"
  on public.articles for select
  to anon, authenticated
  using (true);

create policy "Admins can publish as themselves"
  on public.articles for insert
  to authenticated
  with check ((select public.is_admin()) and author_id = (select auth.uid()));

-- with check stops an author handing an article to someone else
create policy "Authors can edit their own articles"
  on public.articles for update
  to authenticated
  using (author_id = (select auth.uid()))
  with check (author_id = (select auth.uid()));

create policy "Authors can delete their own articles"
  on public.articles for delete
  to authenticated
  using (author_id = (select auth.uid()));

